create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  salon_id uuid not null references public.salons(id) on delete cascade,
  status text not null default 'ativo',
  amount numeric(10, 2) not null default 49.90,
  next_due_date date,
  provider text not null default 'manual',
  provider_subscription_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint subscriptions_salon_unique unique (salon_id),
  constraint subscriptions_status_check check (status in ('ativo', 'inativo', 'suspenso')),
  constraint subscriptions_amount_check check (amount = 49.90)
);

