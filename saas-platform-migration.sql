drop policy if exists "platform owner manages subscriptions" on public.subscriptions;
create policy "platform owner manages subscriptions"
on public.subscriptions
for all
to authenticated
using (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.role = 'platform_owner'
))
with check (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.role = 'platform_owner'
));

drop policy if exists "salon admins read own subscription" on public.subscriptions;
create policy "salon admins read own subscription"
on public.subscriptions
for select
to authenticated
using (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.salon_id = subscriptions.salon_id
));
