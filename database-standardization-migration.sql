create table if not exists public.employee_commission_payments (
  id bigint generated by default as identity primary key,
  salon_id bigint not null,
  employee_id bigint,
  employee_name text not null default '',
  amount numeric not null default 0,
  commission_gross numeric not null default 0,
  advances_total numeric not null default 0,
  payment_method text not null default '',
  notes text,
  period_start date not null,
  period_end date not null,
  paid_at timestamptz not null default now(),
  cash_movement_ids bigint[] not null default '{}',
  advance_ids bigint[] not null default '{}'
);

alter table if exists public.employees
  add column if not exists salon_id bigint,
  add column if not exists name text,
  add column if not exists phone text,
  add column if not exists role text,
  add column if not exists functions text,
  add column if not exists email text,
  add column if not exists login_active boolean not null default false,
  add column if not exists active boolean not null default true,
  add column if not exists created_at timestamptz not null default now();

do $$
begin
  if to_regclass('public.employees') is not null then
    update public.employees
    set
      functions = coalesce(functions, role, ''),
      email = coalesce(email, ''),
      login_active = coalesce(login_active, false),
      active = coalesce(active, true)
    where true;
  end if;
end $$;

alter table if exists public.advances
  add column if not exists salon_id bigint,
  add column if not exists employee_id bigint,
  add column if not exists employee_name text,
  add column if not exists amount numeric not null default 0,
